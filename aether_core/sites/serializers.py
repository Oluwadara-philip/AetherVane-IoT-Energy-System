# AetherVane Sites App — Serializers
# ====================================
# Converts Organization, Site, Device, and Circuit objects to/from JSON.

from rest_framework import serializers
from .models import Organization, Site, Device, Circuit


class CircuitSerializer(serializers.ModelSerializer):
    """Serializer for Circuit objects (individual relay channels)."""
    
    class Meta:
        model = Circuit
        fields = ['id', 'device', 'relay_number', 'name', 'description', 'priority']
        read_only_fields = ['id']


class DeviceSerializer(serializers.ModelSerializer):
    """
    Serializer for Device objects (Vane Nodes).
    
    Includes nested circuits so the frontend can show relay names
    alongside device info in a single API call.
    """
    circuits = CircuitSerializer(many=True, read_only=True)
    site_name = serializers.CharField(source='site.name', read_only=True)
    
    class Meta:
        model = Device
        fields = [
            'id', 'site', 'site_name', 'name', 'mac_address',
            'device_status', 'last_heartbeat', 'circuits', 'created_at'
        ]
        read_only_fields = ['id', 'created_at', 'last_heartbeat']
        # api_token is NOT included here — it should never be exposed in list responses


class DeviceRegistrationSerializer(serializers.ModelSerializer):
    """
    Serializer for registering a new device.
    
    When a super_admin or site_manager registers a new ESP32, they provide:
    - which site it belongs to
    - a name
    - the MAC address (printed on the ESP32 or read via firmware)
    
    The API token is auto-generated by the server and shown once
    (like a password — you see it once, save it, and it's hidden after).
    """
    
    class Meta:
        model = Device
        fields = ['id', 'site', 'name', 'mac_address', 'api_token', 'device_status']
        read_only_fields = ['id', 'api_token', 'device_status']


class SiteSerializer(serializers.ModelSerializer):
    """
    Serializer for Site objects.
    
    Includes device count so the dashboard can show "Factory (3 devices)"
    without making a separate API call.
    """
    device_count = serializers.IntegerField(source='devices.count', read_only=True)
    organization_name = serializers.CharField(source='organization.name', read_only=True)
    
    class Meta:
        model = Site
        fields = ['id', 'organization', 'organization_name', 'name', 'location', 'is_active', 'device_count', 'created_at']
        read_only_fields = ['id', 'created_at']


class OrganizationSerializer(serializers.ModelSerializer):
    """Serializer for Organization objects."""
    site_count = serializers.IntegerField(source='sites.count', read_only=True)
    
    class Meta:
        model = Organization
        fields = ['id', 'name', 'is_active', 'site_count', 'created_at']
        read_only_fields = ['id', 'created_at']
